// Golden vectors: results computed by V8 and by SHAG's own TypeScript, which
// the Rust tests must reproduce bit for bit (RUST.md 18.6).
//
//   node tools/golden/generate.mjs <path to a SHAG checkout> [<path to wash-fps-rust>]
//
// Washoi's own vectors (its snapshot events) go into the second checkout, by
// default ../wash-fps-rust next to this one. The movement vectors run wash-fps's
// own simulation, so wash-fps must be checked out at <shag>/src/games/fps (the
// SHAG submodule, or `git -C <wash-fps> archive <pinned commit> | tar -x -C ...`).
// Needs Node 22.18+ (TypeScript type stripping). Writes into crates/*/tests/golden/.
// Commit the output together with the SHAG commit it was made from.
import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { pathToFileURL } from "node:url";

const shag = resolve(process.argv[2] ?? "../shag");
const root = resolve(import.meta.dirname, "../..");
const washoi = resolve(process.argv[3] ?? resolve(root, "../wash-fps-rust"));
const shagCommit = execFileSync("git", ["-C", shag, "rev-parse", "HEAD"], { encoding: "utf8" }).trim();

// Deterministic generator, so a rerun on the same SHAG commit gives the same file.
let seed = 0x9e3779b9;
function random() {
  seed ^= seed << 13;
  seed ^= seed >>> 17;
  seed ^= seed << 5;
  return (seed >>> 0) / 0x1_0000_0000;
}

const view = new DataView(new ArrayBuffer(8));
function bits(x) {
  view.setFloat64(0, x, true);
  return view.getBigUint64(0, true).toString(16).padStart(16, "0");
}

function header(what) {
  return [
    `# ${what}`,
    `# generated by tools/golden/generate.mjs from SHAG ${shagCommit}, node ${process.version}`,
    "# values are IEEE-754 f64 bit patterns in hex",
    "",
  ];
}

// --- Math.round and Math.hypot -------------------------------------------------
const special = [0, -0, 0.5, -0.5, 1.5, -1.5, 2.5, -2.5, 0.49999999999999994, -0.49999999999999994,
  4503599627370495.5, -4503599627370495.5, 4503599627370497, 1e300, -1e-300, Infinity, -Infinity, NaN,
  Number.MIN_VALUE, -Number.MIN_VALUE, Number.MAX_VALUE];
const round = [...special];
for (let i = 0; i < 2000; i++) round.push((random() - 0.5) * 10 ** Math.floor(random() * 12 - 4));
for (let i = 0; i < 500; i++) round.push(Math.floor((random() - 0.5) * 2000) + 0.5);

const hypot = [[], [3, 4], [0, 0, 0], [1e308, 1e308], [1e-320, 1e-320], [NaN, Infinity], [NaN, 1], [-0, -0],
  [Infinity, -Infinity]];
for (let i = 0; i < 2000; i++) {
  const n = 1 + Math.floor(random() * 3);
  const scale = 10 ** Math.floor(random() * 10 - 5);
  hypot.push(Array.from({ length: n }, () => (random() - 0.5) * 2 * scale));
}
// Inputs shaped like the sanitizer's: a movement direction near unit length.
for (let i = 0; i < 1000; i++) {
  const a = random() * Math.PI * 2;
  const r = 0.9 + random() * 0.2;
  hypot.push([Math.cos(a) * r, Math.sin(a) * r]);
}

const js = header("Math.round and Math.hypot, from V8");
for (const x of round) js.push(`round ${bits(x)} ${bits(Math.round(x))}`);
for (const xs of hypot) js.push(`hypot ${xs.length} ${xs.map(bits).join(" ")} ${bits(Math.hypot(...xs))}`.replace("  ", " "));
writeFileSync(resolve(root, "crates/shagger_shared/tests/golden/js_math.txt"), `${js.join("\n")}\n`);

// --- pk3IndexHash ------------------------------------------------------------
const { pk3IndexHash } = await import(
  pathToFileURL(resolve(shag, "src/engine/loader/pk3/PK3PublishedIndex.ts")).href
);
const texts = ["", "a", "hello", "map_wdm2.pk3:1234|tex_wdm2.pk3:99", "äö€😀", "\u0000￿",
  JSON.stringify({ version: 2, packages: [{ pk3: "map_wdm2.pk3", size: 1 }] })];
const alphabet = "abcdefghijklmnopqrstuvwxyz0123456789_./:|{}\"äöå€😀";
for (let i = 0; i < 300; i++) {
  const chars = [...alphabet];
  let text = "";
  const length = Math.floor(random() * 200);
  for (let j = 0; j < length; j++) text += chars[Math.floor(random() * chars.length)];
  texts.push(text);
}
const pk3 = header("pk3IndexHash, from SHAG src/engine/loader/pk3/PK3PublishedIndex.ts");
pk3[2] = "# each line: the input as UTF-8 hex (\"-\" when empty), then the hash";
for (const text of texts) pk3.push(`${Buffer.from(text, "utf8").toString("hex") || "-"} ${pk3IndexHash(text)}`);
writeFileSync(resolve(root, "crates/shagger/tests/golden/pk3_index_hash.txt"), `${pk3.join("\n")}\n`);

// --- String to number: trim, parseFloat, Number ------------------------------
const numberTexts = ["", " ", "0", "-0", "+0", "1", "1.", ".5", "-.5", ".", "+", "-", "1e", "1e+", "1e5", "1.e5", ".e1",
  "1E-7", "Infinity", "-Infinity", "+Infinity", "Infinityx", "infinity", "inf", "nan", "NaN", "0x10", "0X1f", "0x", "-0x10",
  "0o17", "0b101", "0b2", "0x1fffffffffffff", "0x20000000000001", "0x20000000000003", "0x" + "f".repeat(300), "1_000",
  "  42  ", "\t\n\v\f\r 7", "\u00a0 8\u2028", "\ufeff9", "\u0085" + "10", "\u3000 11 \u205f", "12abc", "abc12",
  "64 64 128", "512", "513", "1e400", "-1e400", "4.9e-324", "2e-324", "0.1", "123456789012345678901234567890",
  "9007199254740993", "1.7976931348623157e308", "1.7976931348623159e308", "00012", "-00.5e-0", "5e", "--5", "+-5", "0.0000001"];
for (let i = 0; i < 400; i++) {
  const pieces = ["", " ", "+", "-", ".", "e", "E", "0", "1", "7", "9", "x", "Infinity", "\u00a0", "\t", "a"];
  let t = "";
  for (let j = Math.floor(random() * 8); j > 0; j--) t += pieces[Math.floor(random() * pieces.length)];
  numberTexts.push(t);
}
const numbers = header("String.prototype.trim, parseFloat and Number on strings");
numbers[2] = "# each line: input as UTF-8 hex (\"-\" when empty), trimmed hex, parseFloat bits, Number bits";
const utf8 = (t) => Buffer.from(t, "utf8").toString("hex") || "-";
for (const t of numberTexts) numbers.push(`${utf8(t)} ${utf8(t.trim())} ${bits(parseFloat(t))} ${bits(Number(t))}`);
writeFileSync(resolve(root, "crates/shagger_shared/tests/golden/js_string_number.txt"), `${numbers.join("\n")}\n`);

// --- Math.sin and Math.cos (own generator, so the files above stay put) ------------
{
  let s = 0x7f4a7c15;
  const r = () => {
    s ^= s << 13;
    s ^= s >>> 17;
    s ^= s << 5;
    return (s >>> 0) / 0x1_0000_0000;
  };
  const inputs = [0, -0, NaN, Infinity, -Infinity, Number.MIN_VALUE, Number.MAX_VALUE, 2 ** 19 * Math.PI / 2];
  for (let k = 1; k < 64; k++) inputs.push((k * Math.PI) / 4, (-k * Math.PI) / 4);
  const scales = [1, Math.PI, 8, 100, 1e6, 1e9, 1e15, 1e22, 1e300, 1e-9];
  for (let i = 0; i < 15000; i++) inputs.push((r() - 0.5) * scales[i % scales.length]);
  for (let i = 0; i < 3000; i++) {
    const v = new DataView(new ArrayBuffer(8));
    v.setUint32(0, (r() * 0x1_0000_0000) >>> 0);
    v.setUint32(4, (r() * 0x1_0000_0000) >>> 0);
    inputs.push(v.getFloat64(0));
  }
  const trig = header("Math.sin and Math.cos, from V8");
  trig[2] = "# each line: x, sin x, cos x as f64 bits";
  for (const x of inputs) trig.push(`${bits(x)} ${bits(Math.sin(x))} ${bits(Math.cos(x))}`);
  writeFileSync(resolve(root, "crates/shagger_shared/tests/golden/js_trig.txt"), `${trig.join("\n")}\n`);
}

// --- Wire protocol (needs TypeScript enums, so it runs in its own Node) --------
const protocolOut = resolve(root, "crates/shagger_shared/tests/golden");
execFileSync(
  process.execPath,
  ["--experimental-transform-types", "--no-warnings", "--import", "./ts-register.mjs", "protocol.mjs", shag, protocolOut, shagCommit, resolve(washoi, "tests/golden")],
  { cwd: import.meta.dirname, stdio: "inherit" },
);

// --- BSP loader ------------------------------------------------------------------
execFileSync(
  process.execPath,
  ["--experimental-transform-types", "--no-warnings", "--import", "./ts-register.mjs", "bsp.mjs", shag, resolve(root, "crates/shagger/tests/golden"), shagCommit],
  { cwd: import.meta.dirname, stdio: "inherit" },
);

// --- Collision (imports @babylonjs/core: SHAG needs its node_modules) -------------
execFileSync(
  process.execPath,
  ["--experimental-transform-types", "--no-warnings", "--import", "./ts-register.mjs", "collision.mjs", shag, resolve(root, "crates/shagger/tests/golden"), shagCommit],
  { cwd: import.meta.dirname, stdio: "inherit" },
);

// --- Washoi movement (needs wash-fps at <shag>/src/games/fps) ---------------------
execFileSync(
  process.execPath,
  ["--experimental-transform-types", "--no-warnings", "--import", "./ts-register.mjs", "movement.mjs", shag, resolve(washoi, "tests/golden"), shagCommit],
  { cwd: import.meta.dirname, stdio: "inherit" },
);

console.log(`wrote ${round.length} round, ${hypot.length} hypot and ${texts.length} pk3IndexHash vectors`);
