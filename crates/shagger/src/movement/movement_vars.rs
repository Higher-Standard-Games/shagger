//! SHAG `src/engine/movement/MovementVars.ts`: the movement, physics and
//! camera variables (`cl_speed`, `m_sensitivity`, `cl_fov`, ...), each a
//! float cvar with its bounds. The browser also mirrors them under
//! `localStorage["engine.movementVars"]`; the cvar file holds the same
//! values here, so one store is enough.

use crate::core::cvar::{CvarOptions, CvarType, Cvars};

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Category {
    Movement,
    Physics,
    Camera,
    Debug,
}

/// `MovementVar`, without the current value (the cvar holds it).
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct MovementVar {
    pub name: &'static str,
    pub default_value: f64,
    pub min: f64,
    pub max: f64,
    pub description: &'static str,
    pub category: Category,
    pub developer_only: bool,
}

/// `registerCvars`: every variable as a float cvar, saved.
pub fn register_movement_vars(cvars: &mut Cvars) {
    for v in DEFAULT_VARS {
        let options = CvarOptions::describe(v.description)
            .range(v.min, v.max)
            .kind(CvarType::Float);
        cvars.register(v.name, v.default_value, options);
    }
}

/// `MovementVars.get`: the cvar's value, or the default before registration.
#[must_use]
pub fn movement_var(cvars: &Cvars, name: &str) -> f64 {
    if cvars.exists(name) {
        cvars.get_number(name)
    } else {
        DEFAULT_VARS
            .iter()
            .find(|v| v.name == name)
            .map_or(0.0, |v| v.default_value)
    }
}

